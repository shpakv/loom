#!/usr/bin/env python3
"""Loom: generate docs/INDEX.md from document frontmatter.

Usage:
  index_gen.py            write docs/INDEX.md
  index_gen.py --print    print the table to stdout only
Naive frontmatter parser (top-level `key: value` between --- fences) — no deps.
"""
import sys
from datetime import date
from pathlib import Path

DOCS = Path("docs")


def frontmatter(path: Path):
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except (UnicodeDecodeError, OSError):
        return None
    if not lines or lines[0].lstrip().startswith("<!-- GENERATED"):
        return None
    if lines[0].strip() != "---":
        return None
    fm = {}
    for line in lines[1:]:
        if line.strip() == "---":
            return fm
        if ":" in line and not line.startswith((" ", "\t", "-")):
            k, _, v = line.partition(":")
            fm[k.strip()] = v.strip()
    return None


def main(argv):
    rows = []
    for f in sorted(DOCS.rglob("*.md")):
        if f.name == "INDEX.md":
            continue
        fm = frontmatter(f)
        if fm and "status" in fm:
            rows.append((fm.get("id", "?"), fm["status"],
                         fm.get("updated", "?"), str(f)))

    lines = [
        "<!-- GENERATED by scripts/loom/index_gen.py — do not edit -->",
        f"# Loom document index ({date.today().isoformat()})", "",
        "| ID | Status | Updated | Path |", "|---|---|---|---|",
    ]
    lines += [f"| {i} | {s} | {u} | {p} |" for i, s, u, p in rows]
    out = "\n".join(lines) + "\n"

    if "--print" in argv:
        print(out)
    else:
        (DOCS / "INDEX.md").write_text(out, encoding="utf-8")
        print(f"wrote docs/INDEX.md ({len(rows)} documents)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
