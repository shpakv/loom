#!/usr/bin/env python3
"""Loom: generate a linked document index and relationship graph.

Nodes are Markdown documents. Edges come from resolved Loom ID references and
local Markdown links. The generated document is a projection, not a source.

Usage:
  doc_graph_gen.py            write docs/DOC-GRAPH.md
  doc_graph_gen.py --print    print the generated document
"""
import html
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path
from urllib.parse import quote, unquote, urlsplit

from config import ConfigError, project_config, require_targets, target, usage
from impact_scan import collect
from link_check import markdown_links


def local_markdown_targets(path, lines):
    """Yield resolved local Markdown targets, ignoring external and asset links."""
    for _, destination in markdown_links(lines):
        try:
            parsed = urlsplit(html.unescape(destination))
        except ValueError:
            continue
        if parsed.scheme or parsed.netloc:
            continue
        target_path = unquote(parsed.path)
        if target_path and Path(target_path).suffix.lower() != ".md":
            continue
        if target_path:
            yield (path.parent / target_path).resolve(), unquote(parsed.fragment)
        elif parsed.fragment:
            yield path.resolve(), unquote(parsed.fragment)


def safe_label(value):
    """Escape text for quoted Mermaid labels."""
    return (value.replace('"', "#quot;").replace("|", "#124;")
            .replace("<", "#lt;").replace(">", "#gt;")
            .replace("\n", " "))


def build_document(docs):
    definitions, refs, file_info = collect(docs, include_changes=True)
    files = sorted(file_info, key=lambda value: value.replace("\\", "/").casefold())
    docs_root = docs.resolve()
    resolved_to_key = {Path(value).resolve(): value for value in files}
    node_ids = {value: f"DOC{index:04d}" for index, value in enumerate(files, 1)}
    edges = defaultdict(set)

    # Semantic references remain authoritative even when their display text is
    # a bare ID rather than a Markdown hyperlink.
    for ref_id, sites in refs.items():
        target_file = definitions.get(ref_id)
        if not target_file:
            continue
        for site in sites:
            source_file = site["file"]
            if source_file != target_file:
                edges[(source_file, target_file)].add(ref_id)
    id_edge_pairs = set(edges)

    # Include ordinary page links too. Avoid adding a generic edge label when
    # the same document pair already has a more meaningful ID edge.
    for source_file in files:
        source = Path(source_file)
        try:
            source_lines = source.read_text(encoding="utf-8").splitlines()
        except (OSError, UnicodeError):
            continue
        for target_path, fragment in local_markdown_targets(source, source_lines):
            target_file = resolved_to_key.get(target_path)
            if target_file and target_file != source_file:
                pair = (source_file, target_file)
                if pair not in id_edge_pairs:
                    edges[pair].add(f"#{fragment}" if fragment else "Markdown link")

    lines = [
        "<!-- GENERATED by scripts/loom/doc_graph_gen.py — do not edit -->",
        f"# Document graph ({date.today().isoformat()})", "",
        "The graph combines resolved Loom ID references and local Markdown links.",
        "Arrows point from a referencing document to the document it references.", "",
        "| Document | Status | Path |", "|---|---|---|",
    ]
    for file_key in files:
        info = file_info[file_key]
        primary_id = info["ids"][0] if info["ids"] else Path(file_key).stem
        relative = Path(file_key).resolve().relative_to(docs_root).as_posix()
        link = quote(relative, safe="/-_.")
        lines.append(
            f"| [{primary_id}]({link}) | {info.get('status') or '—'} | {relative} |"
        )

    lines += ["", "## Relationships", "", "\x60\x60\x60mermaid", "flowchart LR"]
    for file_key in files:
        info = file_info[file_key]
        label = info["ids"][0] if info["ids"] else Path(file_key).stem
        lines.append(f'  {node_ids[file_key]}["{safe_label(label)}"]')
    for (source_file, target_file), labels in sorted(edges.items()):
        label = ", ".join(sorted(labels))
        lines.append(
            f'  {node_ids[source_file]} -->|{safe_label(label)}| {node_ids[target_file]}'
        )
    lines += ["\x60\x60\x60", ""]
    return "\n".join(lines), len(files), len(edges)


def main(argv):
    if "--help" in argv:
        print(usage("doc_graph_gen.py", "[--print|--help]", "Generate the linked document index and relationship graph."))
        return 0
    try:
        config, base = project_config()
        docs = base / target(config, "docs", "docs")
        output = docs / "DOC-GRAPH.md"
    except ConfigError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    for error in require_targets([docs]):
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    document, document_count, edge_count = build_document(docs)
    if "--print" in argv:
        print(document)
    else:
        output.write_text(document, encoding="utf-8")
        print(f"wrote {output} ({document_count} documents, {edge_count} links)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
